import { randomUUID } from 'node:crypto';
import { afterAll, beforeAll, expect, it } from 'vitest';
import request from 'supertest';
import { app } from '../src/app.js';
import { prisma } from '../src/infrastructure/prisma.js';
import { crearFixtureComercial, limpiarFixtureComercial } from './support/comercial-fixtures.js';
let f: Awaited<ReturnType<typeof crearFixtureComercial>>;
const raiz = '/api/fuentes-gerenciales/logistica';
const fecha = (dia: number) => `2011-01-${String(dia).padStart(2, '0')}T00:00:00Z`;
const post = (ruta: string, body: object, key = randomUUID()) => request(app).post(raiz + ruta).set('Authorization', `Bearer ${f.tokens.ADMIN}`).set('Idempotency-Key', key).send(body);
beforeAll(async () => { f = await crearFixtureComercial('H7-CORTE'); });
afterAll(async () => {
    if (f) {
        const propios = { autorId: { in: f.usuarios } };
        await prisma.recepcionGerencial.deleteMany({ where: propios });
        await prisma.lineaCompraGerencial.deleteMany({ where: { compra: propios } });
        await prisma.compraGerencial.deleteMany({ where: propios });
        await prisma.movimientoGerencial.deleteMany({ where: propios });
        await prisma.articuloGerencial.deleteMany({ where: propios });
        await prisma.prestamoHerramientaGerencial.deleteMany({ where: propios });
        await prisma.herramientaGerencial.deleteMany({ where: propios });
        await limpiarFixtureComercial(f);
    }
    await prisma.$disconnect();
});
it('recepción atómica, préstamos históricos y rotación por integral temporal exacta', async () => {
    const articulo = await post('/articulos', { codigo: f.prefijo, nombre: 'Artículo histórico', unidad: 'unidad', minimo: '9.000', apertura: { referencia: f.prefijo + '-AP', fechaEfectiva: fecha(1), cantidad: '10.000', costoUnitario: '2.000000', observacion: 'Apertura histórica documentada' } });
    expect(articulo.status).toBe(201);
    const articuloId = articulo.body.data.id;
    const compra = await post('/compras', { proveedor: 'PROVEEDOR DE PRUEBA', referencia: f.prefijo, fechaEfectiva: fecha(2), lineas: [{ articuloId, cantidad: '5.000', costoUnitario: '3.000000', prometidaEn: fecha(3) }] });
    expect(compra.status).toBe(201);
    const linea = compra.body.data.lineas[0];
    const recibo = { version: linea.version, referencia: f.prefijo + '-REC', cantidad: '2.000', fechaEfectiva: fecha(4) };
    const clave = randomUUID();
    const recibida = await post(`/compras/lineas/${linea.id}/recibir`, recibo, clave);
    expect(recibida.status).toBe(200);
    expect(recibida.body.data.lineas[0]).toMatchObject({ recibido: '2.000', pendiente: '3.000', version: 2 });
    expect((await post(`/compras/lineas/${linea.id}/recibir`, recibo, clave)).body.data.recepciones).toHaveLength(1);
    expect(await prisma.movimientoGerencial.count({ where: { referencia: recibo.referencia.toUpperCase() } })).toBe(1);
    expect((await post(`/movimientos/${recibida.body.data.recepciones[0].movimientoId}/revertir`, { referencia: f.prefijo + '-REV-REC', fechaEfectiva: fecha(5), observacion: 'Una recepción no admite reverso manual' })).status).toBe(409);
    expect((await post(`/compras/lineas/${linea.id}/recibir`, { ...recibo, version: 2, referencia: f.prefijo + '-EXCESO', cantidad: '3.001' })).status).toBe(409);
    expect((await post('/movimientos', { articuloId, tipo: 'CONSUMO', referencia: f.prefijo + '-CON', fechaEfectiva: fecha(6), cantidad: '4.000', observacion: 'Consumo histórico documentado' })).status).toBe(201);
    expect((await post('/movimientos', { articuloId, tipo: 'ENTRADA', referencia: f.prefijo + '-FUT', fechaEfectiva: fecha(12), cantidad: '10.000', costoUnitario: '3.000000', observacion: 'Entrada posterior al corte' })).status).toBe(201);
    expect((await post(`/compras/lineas/${linea.id}/cancelar-pendiente`, { version: 2, fechaEfectiva: fecha(15), motivo: 'Cancelación posterior al corte' })).status).toBe(200);
    const herramienta = await post('/herramientas', { codigo: f.prefijo, nombre: 'Herramienta de prueba histórica' });
    expect(herramienta.status).toBe(201);
    const prestamo = await post(`/herramientas/${herramienta.body.data.id}/prestar`, { empleadoId: f.empleados[0], referencia: f.prefijo, prestadaEn: fecha(2), previstaEn: fecha(5) });
    expect(prestamo.status).toBe(200);
    const loanId = prestamo.body.data.prestamos[0].id;
    expect((await post(`/herramientas/${herramienta.body.data.id}/prestar`, { empleadoId: f.empleados[0], referencia: f.prefijo + '-DOBLE', prestadaEn: fecha(3), previstaEn: fecha(6) })).status).toBe(409);
    expect((await post(`/prestamos/${loanId}/devolver`, { devueltaEn: fecha(15), observacion: 'Devolución posterior al corte' })).status).toBe(200);
    const respuesta = await request(app).get('/api/inteligencia/logistico').query({ desde: fecha(1), hasta: fecha(11) }).set('Authorization', `Bearer ${f.tokens.ADMIN}`);
    expect(respuesta.status).toBe(200);
    const board = respuesta.body.data;
    const metricas = Object.fromEntries(board.metricas.map((m: { clave: string; valor: unknown }) => [m.clave, m.valor]));
    expect(metricas).toMatchObject({ stock_critico_cantidad: 1, compras_pendientes_cantidad: 1, herramientas_prestadas: 1, herramientas_vencidas: 1, inventario_valorizado: '17.333333333' });
    const stock = board.desgloses.find((r: { tipo: string; id: number }) => r.tipo === 'ARTICULO' && r.id === articuloId);
    expect(stock).toMatchObject({ stock: '8.000', valor: '17.333333333', consumoNeto: '4.000', stockMedio: '9.400000', rotacion: '0.425532' });
    expect(board.desgloses.find((r: { tipo: string }) => r.tipo === 'COMPRA_LINEA')).toMatchObject({ pendiente: '3.000', cancelado: '0.000' });
    expect(board.desgloses.find((r: { tipo: string }) => r.tipo === 'RECEPCION')).toMatchObject({ tardia: true });
    expect(board.desgloses.find((r: { tipo: string }) => r.tipo === 'HERRAMIENTA')).toMatchObject({ prestamoId: loanId, vencida: true });
});
